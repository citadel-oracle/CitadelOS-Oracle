class DedicatedCanonicalFeatureRegistry:
    def __init__(self, features: Sequence[CanonicalFeatureMetadata] = CORE_CANONICAL_FEATURES):
        self._registry: dict[str, CanonicalFeatureMetadata] = {f.canonical_name: f for f in features}

    def get(self, canonical_name: str) -> Optional[CanonicalFeatureMetadata]:
        return self._registry.get(canonical_name)

    def list_all(self) -> list[CanonicalFeatureMetadata]:
        return list(self._registry.values())

    def get_by_cluster(self, cluster_name: str) -> list[CanonicalFeatureMetadata]:
        return [f for f in self._registry.values() if f.feature_cluster == cluster_name]

    def export_inventory_artifact(self, output_path: str = "artifacts/canonical_foundation/feature_registry.json") -> dict[str, Any]:
        artifact = {
            "schema_version": "1.0.0",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "total_registered_features": len(self._registry),
            "features": [f.to_dict() for f in self._registry.values()],
            "clusters": list(set(f.feature_cluster for f in self._registry.values())),
        }
        out_file = Path(output_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        with open(out_file, "w") as f:
            json.dump(artifact, f, indent=2)
        return artifact
