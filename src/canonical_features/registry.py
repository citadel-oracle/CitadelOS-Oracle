@dataclass(frozen=True)
class CanonicalFeatureMetadata:
    canonical_name: str
    meaning: str
    owner_engine: str
    source_data: str
    instrument: str
    timeframe: str
    unit: str
    normalization: str
    update_cadence: str
    warm_up: str
    stale_threshold: float
    missing_data_state: str
    valid_range: str
    directionality: str
    downstream_consumers: Sequence[str]
    historical_availability: str
    live_availability: str
    feature_cluster: str
    producer_file: str = "src/canonical_features/engine.py"
    producer_function: str = "CanonicalFeatureEngine.evaluate()"
    source_field: str = "close"
    runtime_wired: bool = True
    last_observed_timestamp: str = ""
    evidence_state: str = "VERIFIED_PRODUCTION"

    def to_dict(self) -> dict[str, Any]:
        return {
            "canonical_name": self.canonical_name,
            "meaning": self.meaning,
            "owner_engine": self.owner_engine,
            "source_data": self.source_data,
            "instrument": self.instrument,
            "timeframe": self.timeframe,
            "unit": self.unit,
            "normalization": self.normalization,
            "update_cadence": self.update_cadence,
            "warm_up": self.warm_up,
            "stale_threshold": self.stale_threshold,
            "missing_data_state": self.missing_data_state,
            "valid_range": self.valid_range,
            "directionality": self.directionality,
            "downstream_consumers": list(self.downstream_consumers),
            "historical_availability": self.historical_availability,
            "live_availability": self.live_availability,
            "feature_cluster": self.feature_cluster,
            "producer_file": self.producer_file,
            "producer_function": self.producer_function,
            "source_field": self.source_field,
            "runtime_wired": self.runtime_wired,
            "last_observed_timestamp": self.last_observed_timestamp or datetime.now(timezone.utc).isoformat(),
            "evidence_state": self.evidence_state,
        }


